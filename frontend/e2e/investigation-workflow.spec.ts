import { test,expect } from '@playwright/test';
import { readFile,writeFile } from 'node:fs/promises';
test('real scoped AI answer and original source field',async({page,request})=>{
  test.setTimeout(240000);
  const sample=JSON.parse(await readFile('../artifacts/verification/public-demo.json','utf8'));
  await page.goto('/');
  await page.getByLabel('Project',{exact:true}).selectOption(sample.project_id);
  await expect(page.getByLabel('Snapshot',{exact:true})).toContainText('0.0.50');
  await page.getByLabel('Snapshot',{exact:true}).selectOption(sample.snapshot_id);
  await expect(page.getByLabel('Advisory query run')).toContainText('2026');
  await page.getByLabel('Advisory query run').selectOption(sample.run_id);
  await page.getByRole('button',{name:'AI investigation',exact:true}).click();
  await page.getByLabel('Retrieval method').selectOption('lexical');
  await page.getByLabel('Investigation question').fill('How many recorded instances are in this snapshot? Report the instances metric.');
  await expect(page.getByRole('button',{name:'Ask with evidence'})).toBeEnabled();
  const submitted=page.waitForResponse(response=>response.url().endsWith('/api/investigations')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Ask with evidence'}).click();
  const payload=await(await submitted).json();
  let job:any;
  await expect.poll(async()=>{job=await(await request.get('/api/jobs/'+payload.job_id)).json();return job.status;},{timeout:210000,intervals:[500,1000,2000]}).toBe('ready');
  const result=await(await request.get('/api/investigations/'+job.result_id)).json();
  await writeFile('../artifacts/verification/ai-browser-attempt-'+result.id+'.json',JSON.stringify(result,null,2)+'\n');
  if(result.answer.status==='answered')await writeFile('../artifacts/verification/ai-browser-result.json',JSON.stringify(result,null,2)+'\n');
  expect(result.answer.status).toBe('answered');
  expect(result.answer.facts.some((fact:any)=>fact.kind==='count'&&fact.value.metric==='instances'&&fact.value.count===41)).toBeTruthy();
  await expect(page.getByTestId('investigation-answer')).toContainText('Evidence-based answer');
  await expect(page.getByTestId('investigation-answer')).toHaveAttribute('data-snapshot-id',sample.snapshot_id);
  await page.screenshot({path:'../artifacts/verification/ai-desktop.png',fullPage:true});
  await page.getByRole('button',{name:/Evidence 1 /}).click();
  await expect(page.getByRole('heading',{name:'Original source field verified'})).toBeVisible();
  await expect(page.locator('.source-proof')).toContainText('/text');
  await page.screenshot({path:'../artifacts/verification/ai-source-proof.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'../artifacts/verification/ai-mobile.png',fullPage:true});
});
